-- 1단계: schema.dbml 기준 Oracle 12c 이상 테이블 및 제약조건 생성.
-- 빈 스키마에서 실행한다. 기존 테이블이 있다면 다시 실행하지 않는다.
-- 실행 순서: 01_create_tables.sql -> 02_insert.sql -> 03_update.sql(선택).
-- board의 date는 Oracle 예약어이므로 큰따옴표로 감싼 소문자 식별자를 사용한다.

WHENEVER SQLERROR EXIT FAILURE ROLLBACK
SET DEFINE OFF

CREATE TABLE review (
    review_id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    title VARCHAR2(200 CHAR) NOT NULL,
    content CLOB NOT NULL,
    writer VARCHAR2(50 CHAR) NOT NULL,
    "date" TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    product_id NUMBER(19) NOT NULL,
    file_name VARCHAR2(255 CHAR),
    file_type VARCHAR2(255 CHAR),
    file_data BLOB,
    CONSTRAINT pk_review PRIMARY KEY (review_id)
);

CREATE TABLE member (
    member_id VARCHAR2(50 CHAR) NOT NULL,
    member_name VARCHAR2(100 CHAR) NOT NULL,
    password VARCHAR2(255 CHAR) NOT NULL,
    email VARCHAR2(254 CHAR),
    joined_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT pk_member PRIMARY KEY (member_id)
);

CREATE TABLE order_item (
    order_id NUMBER(19) NOT NULL,
    product_id NUMBER(19) NOT NULL,
    quantity NUMBER(19) NOT NULL,
    unit_price NUMBER(12,2) NOT NULL,
    CONSTRAINT pk_order_item PRIMARY KEY (order_id, product_id),
    CONSTRAINT ck_order_item_price CHECK (unit_price >= 0),
    CONSTRAINT ck_order_item_quantity CHECK (quantity > 0)
);

CREATE TABLE orders (
    order_id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    member_id VARCHAR2(50 CHAR) NOT NULL,
    ordered_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT pk_orders PRIMARY KEY (order_id)
);

CREATE TABLE product (
    product_id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    product_name VARCHAR2(200 CHAR) NOT NULL,
    price NUMBER(12,2) NOT NULL,
    seller_id NUMBER(19) NOT NULL,
    CONSTRAINT pk_product PRIMARY KEY (product_id),
    CONSTRAINT ck_product_price CHECK (price >= 0)
);

CREATE TABLE seller (
    seller_id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    seller_name VARCHAR2(100 CHAR) NOT NULL,
    email VARCHAR2(254 CHAR),
    phone VARCHAR2(20 CHAR),
    registered_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT pk_seller PRIMARY KEY (seller_id)
);

ALTER TABLE review ADD CONSTRAINT fk_review_member FOREIGN KEY (writer) REFERENCES member (member_id);
ALTER TABLE review ADD CONSTRAINT fk_review_product FOREIGN KEY (product_id) REFERENCES product (product_id);
ALTER TABLE order_item ADD CONSTRAINT fk_order_item_orders FOREIGN KEY (order_id) REFERENCES orders (order_id);
ALTER TABLE order_item ADD CONSTRAINT fk_order_item_product FOREIGN KEY (product_id) REFERENCES product (product_id);
ALTER TABLE orders ADD CONSTRAINT fk_orders_member FOREIGN KEY (member_id) REFERENCES member (member_id);
ALTER TABLE product ADD CONSTRAINT fk_product_seller FOREIGN KEY (seller_id) REFERENCES seller (seller_id);

